def normalize_article_type(article_type):
    if article_type is None:
        return ''
    key = str(article_type).strip()
    if key in AFFINITY:
        return key
    key_lower = key.lower()
    if key_lower in _AFFINITY_KEY_BY_LOWER:
        return _AFFINITY_KEY_BY_LOWER[key_lower]
    if key_lower in _VI_TO_EN_LOWER:
        return _VI_TO_EN_LOWER[key_lower]
    return key


def get_user_group(gender, birth_year):
    g = str(gender).lower() if gender is not None else ''
    try:
        y = int(birth_year)
    except Exception:
        y = None

    if g == 'female':
        if y is not None and y >= 2000:
            return 'yf'
        if y is not None and y < 2000:
            return 'af'
    if g == 'male':
        if y is not None and y >= 2000:
            return 'ym'
        if y is not None and y < 2000:
            return 'am'
    return None
